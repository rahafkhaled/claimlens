const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const url = process.env.CLAIMLENS_URL || 'http://127.0.0.1:3184';
(async () => {
 const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
 try {
  const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors=[]; p.on('pageerror', e=>errors.push(e.message));
  await p.addInitScript(() => {
   const original = window.fetch;
   window.reviewRequests=[];
   window.fetch = (url, options) => {
    if (url !== '/api/analyze') return original(url,options);
    window.reviewRequests.push(JSON.parse(options.body));
    return Promise.resolve(new Response(new ReadableStream({start(c){window.reviewController=c;}}),{headers:{'Content-Type':'application/x-ndjson'}}));
   };
   window.reviewEmit = (events, close=false) => { for(const event of events) window.reviewController.enqueue(new TextEncoder().encode(JSON.stringify(event)+'\n')); if(close)window.reviewController.close(); };
  });
  await p.goto(url);
  await p.waitForFunction(()=>!document.querySelector('nav[aria-label="Claims"] .secondary').disabled);
  assert.equal(await p.getByRole('button',{name:'Evidence 6',exact:true}).getAttribute('aria-current'), 'page');
  assert.equal(await p.locator('.estimate-slip').count(), 0);
  assert.deepEqual(await p.locator('nav[aria-label="Claim sections"] button').allTextContents(), ['Evidence6', 'Estimate', 'History']);
  assert((await p.getByRole('region', {name:'Accident description'}).innerText()).includes('front-left corner'));
  assert.equal(await p.locator('.region-pin,.region-outline').count(),0);
  await p.getByRole('button',{name:'Review evidence',exact:true}).click();
  const flow=p.getByRole('dialog',{name:'Claim workflow'});
  await p.waitForFunction(()=>window.reviewRequests.length===1);
  assert((await p.evaluate(()=>window.reviewRequests[0].accidentDescription)).includes('front-left corner'));
  assert.equal(await flow.locator('.decision-branch[data-selected="true"]').count(),0);
  assert.equal(await flow.locator('.decision-receipt').innerText(),'Decision pending');
  await p.evaluate(()=>window.reviewEmit([{type:'stage',stage:'quality'}]));
  await flow.getByText('LLM is reviewing photos',{exact:true}).waitFor();
  await p.evaluate(()=>window.reviewEmit([{type:'quality',quality:{summary:'Clear exterior views.',gaps:[]}},{type:'stage',stage:'decision'}]));
  await flow.getByText('Decision Model is deciding the route',{exact:true}).waitFor();
  assert.equal(await flow.locator('.model-decision').getAttribute('data-state'),'active');
  await p.screenshot({path:'/tmp/claimlens-jev-active.png',animations:'disabled'});
  await p.evaluate(()=>window.reviewEmit([{type:'decision',decision:{choice:'sufficient',confidence:.97}},{type:'result',data:{quality:{summary:'Clear exterior views.',gaps:[]},decision:{choice:'sufficient',confidence:.97}}}],true));
  await p.waitForFunction(()=>window.reviewRequests.length===2);
  await flow.getByText('97% confidence',{exact:true}).waitFor();
  assert((await flow.locator('.decision-branch[data-selected="true"]').innerText()).includes('Sufficient'));
  await p.evaluate(()=>window.reviewEmit([{type:'stage',stage:'damage'}]));
  await flow.getByRole('button',{name:'Keep reviewing in background'}).click();
  await p.getByRole('button',{name:/View workflow/}).waitFor();
  await p.evaluate(()=>window.reviewEmit([{type:'findings',count:1},{type:'stage',stage:'pricing'}]));
  await p.getByRole('button',{name:/View workflow/}).click();
  await flow.getByText('Matching catalogue entries',{exact:true}).waitFor();
  await p.evaluate(()=>window.reviewEmit([{type:'priced',count:1,unpriced:0},{type:'result',data:{findings:[{component:'Right tail lamp',code:'taillamp',damage:'Cracked lens',repair:'Replace tail lamp',operation:'Replace',severity:'Moderate',evidence:[{item:5,box:[100,100,800,800]}]}],lines:[{component:'Right tail lamp',repair:'Replace tail lamp',parts:1456,labor:327.6,source:'Added demo allowance',catalogueId:'taillamp:Replace',needsQuote:false}]}}],true));
  await flow.getByText('Review complete',{exact:true}).waitFor();
  assert(!(await flow.innerText()).match(/Gemini|Jev/));
  await flow.getByText('LLM',{exact:true}).waitFor();
  await flow.getByText('Decision Model',{exact:true}).waitFor();
  assert.equal(await flow.locator('.review-automated .review-node[data-state="done"]').count(),5);
  await p.screenshot({path:'/tmp/claimlens-flow-desktop.png',animations:'disabled'});
  await flow.getByRole('button',{name:'Review estimate',exact:true}).click();
  await p.getByRole('button',{name:'Pricing catalogue',exact:true}).click();
  const catalog=p.getByRole('dialog',{name:'Pricing catalogue'});
  await catalog.getByLabel('Search catalogue').fill('tail lamp');
  assert.equal(await catalog.locator('tbody tr').count(),4);
  assert((await catalog.locator('tbody').innerText()).includes('1,783.60'));
  await catalog.getByLabel('Catalogue operation').selectOption('Inspect');
  assert.equal(await catalog.locator('tbody tr').count(),1);
  await catalog.getByLabel('Search catalogue').fill('calibration');
  assert(!(await catalog.locator('tbody').innerText()).includes('Quote required'));
  assert((await catalog.locator('tbody').innerText()).includes('655.20'));
  await catalog.getByLabel('Search catalogue').fill('');
  await catalog.getByLabel('Catalogue operation').selectOption('all');
  assert.equal(await catalog.locator('tbody tr').count(),96);
  await catalog.getByRole('button',{name:'Close dialog'}).click();
  await p.setViewportSize({width:375,height:812});
  await p.emulateMedia({reducedMotion:'reduce'});
  await p.getByRole('button',{name:'Workflow',exact:true}).click();
  await p.screenshot({path:'/tmp/claimlens-flow-mobile.png'});
  assert.equal(await flow.evaluate(el=>el.scrollWidth>el.clientWidth),false);
  assert.equal(await flow.locator('.decision-branch[data-selected="true"]').evaluate(el=>getComputedStyle(el).transform),'none');
  assert(await flow.locator('.decision-branch').first().evaluate(el=>getComputedStyle(el).transitionDuration.split(',').every(duration=>parseFloat(duration)<=0.00001)));
  await flow.getByRole('button',{name:'Review estimate',exact:true}).scrollIntoViewIfNeeded();
  assert(await flow.getByRole('button',{name:'Review estimate',exact:true}).isVisible());
  await flow.getByRole('button',{name:'Close',exact:true}).click();
  await p.getByRole('button',{name:'Pricing catalogue',exact:true}).click();
  assert.equal(await catalog.evaluate(el=>el.scrollWidth>el.clientWidth),false);
  assert.deepEqual(errors,[]);
  console.log('PASS: true staged stream UI, no stale Jev decision, decision confidence/branch, background continuation, pricing receipt, complete priced catalogue and operation filters, desktop/mobile, reduced motion.');
 } finally { await b.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
